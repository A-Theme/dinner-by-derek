  /* ======================================================================
     Fermenting, canning, drying.
     ----------------------------------------------------------------------
     EVERYTHING IN THIS SECTION CAN MAKE SOMEONE SERIOUSLY ILL IF IT IS DONE
     WRONG, and unlike a badly seasoned sauce it will not look or taste wrong
     when it is. That is the whole reason these are written out rather than
     left to memory.

     The one rule that governs the canning entries: pH 4.6. At or below it,
     acid stops Clostridium botulinum growing and a boiling water bath is
     enough. Above it -- vegetables, meat, most soups and sauces -- boiling
     does NOT kill the spores, and only a pressure canner reaching about
     116 C does. There is no clever workaround, no amount of extra boiling
     that substitutes, and oven canning and jar inversion are not methods.

     Fermenting is safer than it sounds because the acid the ferment produces
     protects it, but only while the food stays under its brine and the salt
     is actually weighed.

     Drying preserves by removing water, not by killing anything. Meat is the
     exception and gets its own heat step.

     And selling any of this is a different question from making it. In
     Ontario a low-acid canned product made for sale sits under federal and
     provincial food regulation, and the local public health unit is the
     authority on what a given kitchen may sell. These entries document
     technique; they are not permission.
     ====================================================================== */

